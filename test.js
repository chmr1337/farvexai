  function setLang(l) {
    document.documentElement.setAttribute('data-lang', l);
    localStorage.setItem('farvex_lang', l);
    
    document.getElementById('btnEN').classList.toggle('active', l==='en');
    document.getElementById('btnNL').classList.toggle('active', l==='nl');
    
    const d = T[l];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const k = el.getAttribute('data-i18n');
      if(d[k] !== undefined) el.innerHTML = d[k];
    });
  }

  // Init lang on load
  document.addEventListener("DOMContentLoaded", () => {
    const savedLang = localStorage.getItem('farvex_lang') || 'en';
    setLang(savedLang);
  });

  // Terminal Demo Logic
  function runTerminalDemo() {
    const btn = document.querySelector('.demo-terminal button');
    if(btn.disabled) return;
    btn.disabled = true;
    
    const lang = document.documentElement.getAttribute('data-lang') || 'en';
    const promptText = lang === 'nl' 
      ? "Analyseer financieel rapport Q3 en haal omzet en marge eruit." 
      : "Analyze Q3 financial report and extract revenue and margin.";
      
    const aiJson = `{
    "status": "success",
    "data": {
      "document": "Q3_Financial_Report.pdf",
      "metrics": {
        "revenue": "$4.2M",
        "margin": "22.5%"
      },
      "sentiment": "Positive"
    },
    "confidence": 0.98
  }`;

    const promptEl = document.getElementById('termPrompt');
    const cursorEl = document.getElementById('termCursor');
    const spinnerEl = document.getElementById('termSpinner');
    const aiEl = document.getElementById('termAi');
    const aiTextEl = document.getElementById('termAiText');
    const spinChar = document.getElementById('spinChar');
    
    promptEl.innerHTML = '';
    promptEl.appendChild(cursorEl);
    aiEl.style.display = 'none';
    spinnerEl.style.display = 'none';
    aiTextEl.innerHTML = '';
    
    let i = 0;
    function typePrompt() {
      if (i < promptText.length) {
        cursorEl.insertAdjacentText('beforebegin', promptText.charAt(i));
        i++;
        setTimeout(typePrompt, 30);
      } else {
        setTimeout(startSpinner, 300);
      }
    }
    
    let spinInterval;
    function startSpinner() {
      spinnerEl.style.display = 'block';
      const chars = ['|', '/', '-', '\\\\'];
      let c = 0;
      spinInterval = setInterval(() => {
        spinChar.innerText = chars[c % chars.length];
        c++;
      }, 100);
      
      setTimeout(() => {
        clearInterval(spinInterval);
        spinnerEl.style.display = 'none';
        startAiResponse();
      }, 1500);
    }
    
    let j = 0;
    function startAiResponse() {
      aiEl.style.display = 'block';
      function typeJson() {
        if (j < aiJson.length) {
          let char = aiJson.charAt(j);
          if (char === '\\n') {
            aiTextEl.innerHTML += '<br>&nbsp;&nbsp;';
          } else if (char === ' ') {
             aiTextEl.innerHTML += '&nbsp;';
          } else {
            aiTextEl.innerHTML += char;
          }
          j++;
          setTimeout(typeJson, 15);
        } else {
          btn.disabled = false;
        }
      }
      typeJson();
    }
    
    typePrompt();
  }
